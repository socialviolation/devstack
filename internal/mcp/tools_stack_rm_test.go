package mcp

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/socialviolation/devstack/internal/stack"
	"github.com/socialviolation/devstack/internal/workspace"
)

func TestStackRmOnAnUpStackDropsItFromTheHostTiltfile(t *testing.T) {
	ws, _, _ := seedStack(t)
	serveHostDaemon(t)
	if err := stack.SetActive(ws.Name, "feat", true); err != nil {
		t.Fatalf("activate stack: %v", err)
	}

	hostPath := filepath.Join(workspace.HostTiltDir(), "Tiltfile")
	writeFile(t, hostPath, "# GENERATED BY devstack\n\n# testws:api:feat\nlocal_resource(\n    \"testws:api:feat\",\n    serve_cmd=\"go run .\",\n)\n")

	removeStack(ws, "feat", true)

	data, err := os.ReadFile(hostPath)
	if err != nil {
		t.Fatalf("read host Tiltfile: %v", err)
	}
	if strings.Contains(string(data), "testws:api:feat") {
		t.Fatalf("stack_rm left the stack's resource in the host Tiltfile:\n%s", data)
	}
	recs, err := stack.LoadStore(ws.Name)
	if err != nil {
		t.Fatalf("load store: %v", err)
	}
	for _, r := range recs {
		if r.Name == "feat" && r.Active {
			t.Fatalf("stack_rm left the stack active after the removal failed")
		}
	}
}
